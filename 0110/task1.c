#include <stdio.h>    // 引入标准输入输出头文件，用于printf 输出、fgets 输入
#include <string.h>   // 引入字符串处理头文件，用于strlen()计算字符串长度
#include <stdlib.h>   // 引入标准库头文件，本代码暂未用到，保留不影响

int main(int argc, char const *argv[])
{
    char a[16];       // 定义字符数组，存储用户输入的阿拉伯数字金额，最多存15位数字+结束符，支持千亿级
    // 数字映射数组：下标0对应"零"，下标1对应"壹"...下标9对应"玖"，阿拉伯数字转中文大写数字核心映射表
    char *p[] = {"零", "壹", "贰", "叁", "肆", "伍", "陆", "柒", "捌", "玖"};
    // 单位映射数组标准单位【千 佰 拾 亿 千 佰 拾 万 千 佰 拾】，固定顺序不可改
    // 对应数字位数：千亿 百亿 十亿 亿 千万 百万 十万 万 千 百 十 位，共11个单位，适配12位数字
    char *p1[] = {"千", "佰", "拾", "亿", "千", "佰", "拾", "万", "千", "佰", "拾"};
    
    printf("请输入金额: ");          // 提示用户输入
    fgets(a, 15, stdin);            // 安全读取用户输入的数字，最多读14位有效数字，避免缓冲区溢出，读取到回车结束
    int len = strlen(a) - 1;        // 计算输入数字的【有效长度】，strlen含回车符，所以-1去掉回车符，得到真实数字位数
    int c = len;                    // 核心变量c：记录【当前数字的剩余位数】，从高位→低位遍历，初始值=总位数，每遍历1位减1
    // 核心变量t：单位数组p1的下标偏移量，计算当前数字应该匹配哪个中文单位，12-c是核心公式，适配输入数字的长度对应到正确单位位
    // 核心变量s：连续零的计数器，控制连续多个0只输出1个"零"，屏蔽多余零，初始值=0
    // 变量u：仅做遍历计数，本代码暂未用到该变量，保留不影响逻辑
    int t = 12 - c, s = 0, u = 0;
    
    // 核心循环：逐位遍历用户输入的阿拉伯数字，从【最高位】到【最低位】处理每一位数字
    for (int i = 0; i < len; i++)
    {
        // 容错处理：如果输入中包含空格，原样输出空格并跳过本次循环，不做任何处理
        if (a[i] == ' ')
        {
            printf(" ");
            continue;
        }
        
        int r = a[i] - '0';         // 核心转换：将字符型数字(如'5')转为整型数字(如5)，ASCII码运算规则

        // ========== 核心判断1：判断【当前0是否是数字尾部的连续0】 ==========
        // 业务规则：数字末尾的连续0，不需要输出"零"，比如 1000 → 壹仟 ，而非 壹仟零零零
        int is_tail_zero = 1;       // 标记：1=是尾部零  0=不是尾部零，初始默认是尾部零
        if (r == 0)                 // 只有当前位是0时，才需要判断是否是尾部零
        {
            // 从当前位开始，遍历后面所有的数字
            for (int j = i; j < len; j++)
            {
                if (a[j] != '0')    // 如果后面还有非0的数字
                {
                    is_tail_zero = 0;// 说明当前0不是尾部零，取消标记
                    break;          // 跳出循环，无需继续判断
                }
            }
            if (is_tail_zero)       // 如果确认是尾部连续0
            {
                s = 99;             // 锁死连续零计数器为99，后续彻底屏蔽"零"的输出，核心技巧
            }
        }

        // ========== 核心判断2：更新【连续零计数器】 ==========
        // 业务规则：连续多个0，只允许输出1个"零"，比如 1005 → 壹仟零伍 ，而非 壹仟零零伍
        if (r == 0)                 // 当前位是0 → 连续零计数+1
        {
            s++;
        }
        else                        // 当前位不是0 → 连续零计数清零，重新开始计数
        {
            s = 0;
        }

        // ========== 核心判断3：控制【零的输出规则】 s<=1 表示允许输出数字/零 ==========
        // s<=1 两种情况：①当前位非0 ②当前位是0但属于第一个连续零 → 都需要输出对应内容
        if (s <= 1)
        {
            // 特殊规则1：当剩余位数c=5时，对应【万位】，即使万位是0，也必须输出"万"
            // 场景：100000 → 壹拾万 ，而非 壹拾零零零零零
            if (c == 5 && r == 0)
            {
                printf("万");       // 强制输出单位"万"
                s = 99;             // 锁死计数器，后续零不再输出，屏蔽多余零
            }
            // 特殊规则2：当剩余位数c=9时，对应【亿位】，且不是数字首位时，即使亿位是0，也必须输出"亿"
            // 场景：100000000 → 壹亿 ，而非 壹零零零零零零零零
            else if (c == 9 && i != 0 && r == 0)
            {
                printf("亿");       // 强制输出单位"亿"
                s = 99;             // 锁死计数器，后续零不再输出，屏蔽多余零
            }
            // 正常情况：非亿/万补位的普通数字 → 输出对应的中文大写数字
            else
            {
                printf("%s", *(p + r)); // 通过指针取值，等价于 p[r]，数字映射输出
            }
        }
        // ========== 核心判断4：连续零超过1个时，屏蔽多余零的输出 ==========
        // s>1 表示连续零的个数≥2 → 让计数器-1，不输出任何内容，实现"多个零只显示一个"的效果
        if (s > 1)
        {
            s--;
        }

        // ========== 核心判断5：控制【中文单位的输出规则】 ==========
        // 规则：①当前数字不是0 ②剩余位数>1(不是个位) → 才输出对应的中文单位
        // 原因：个位没有单位；数字是0时，不输出单位，比如 10 → 壹拾 ，而非 壹零拾
        if (r != 0 && c > 1)
        {
            printf("%s", *(p1 + t)); // 通过指针取值，等价于 p1[t]，单位映射输出
        }

        t++;    // 单位数组下标+1，为下一位数字匹配下一个单位
        --c;    // 剩余位数-1，遍历下一位数字
        u++;    // 遍历计数器+1，本代码未使用该变量，保留即可
    }
    printf("%s","元整");  // 换行后，打印用户原始输入的数字，方便核对转换结果是否正确
    return 0;           // 程序正常执行完毕，返回0
}